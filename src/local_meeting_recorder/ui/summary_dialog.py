"""Read-only AI meeting summary viewer, with a Regenerate action.

Shows only the latest ``MeetingSummary`` version; earlier versions are preserved on disk
(``SummarySet.versions``, see ``summarization/store.py``) but are not browsable here —
a version picker is a reasonable future addition, not something this pass needs.

One dialog, built fresh each time it's shown — same reasoning as ``transcript_dialog.py``.
"""

from __future__ import annotations

from collections.abc import Callable

from PySide6.QtWidgets import (
    QDialog,
    QHBoxLayout,
    QLabel,
    QPlainTextEdit,
    QPushButton,
    QVBoxLayout,
    QWidget,
)

from local_meeting_recorder.domain.session_metadata import SessionMetadata, SummaryStatus
from local_meeting_recorder.summarization.models import MeetingSummary

RegenerateFn = Callable[[], None]


def show_summary_dialog(
    metadata: SessionMetadata,
    summary: MeetingSummary | None,
    *,
    version_count: int = 0,
    on_regenerate: RegenerateFn | None = None,
    parent: QWidget | None = None,
) -> None:
    dialog = QDialog(parent)
    dialog.setWindowTitle(f"Summary — {metadata.title or metadata.session_id}")
    dialog.resize(640, 560)
    layout = QVBoxLayout(dialog)

    status = metadata.post_processing.summary_status
    if status is SummaryStatus.FAILED:
        message = metadata.post_processing.summary_error or "Summary generation failed."
        layout.addWidget(QLabel(f"Summary generation failed: {message}"))
    elif summary is not None:
        layout.addWidget(QLabel(f"Generated by {summary.provider} ({summary.model_name})"))
        if version_count > 1:
            note = QLabel(f"{version_count - 1} earlier version(s) preserved on disk.")
            note.setWordWrap(True)
            layout.addWidget(note)
        body = QPlainTextEdit()
        body.setReadOnly(True)
        body.setPlainText(_render_summary(summary))
        layout.addWidget(body)
    else:
        layout.addWidget(QLabel("No summary available yet."))

    buttons = QHBoxLayout()
    buttons.addStretch(1)
    if on_regenerate is not None:

        def _regenerate_and_close() -> None:
            on_regenerate()
            dialog.accept()

        label = "Regenerate Summary" if summary is not None else "Generate Summary"
        regenerate_button = QPushButton(label)
        regenerate_button.clicked.connect(_regenerate_and_close)
        buttons.addWidget(regenerate_button)
    close_button = QPushButton("Close")
    close_button.clicked.connect(dialog.accept)
    buttons.addWidget(close_button)
    layout.addLayout(buttons)

    dialog.exec()


def _render_summary(summary: MeetingSummary) -> str:
    lines = [summary.title, "", summary.executive_summary]
    if summary.topics:
        lines += ["", "Topics:", *(f"  - {t}" for t in summary.topics)]
    if summary.decisions:
        lines += ["", "Decisions:", *(f"  - {d.description}" for d in summary.decisions)]
    if summary.action_items:
        lines += ["", "Action Items:"]
        for item in summary.action_items:
            detail = ""
            if item.owner:
                detail += f" (owner: {item.owner})"
            if item.deadline:
                detail += f" (due: {item.deadline})"
            lines.append(f"  - {item.description}{detail}")
    if summary.risks:
        lines += ["", "Risks:", *(f"  - {r}" for r in summary.risks)]
    if summary.follow_ups:
        lines += ["", "Follow-ups:", *(f"  - {f}" for f in summary.follow_ups)]
    return "\n".join(lines)
